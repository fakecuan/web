-- D.VA SKATE Order Management
-- Jalankan seluruh SQL ini di Supabase Dashboard > SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  size_details text not null,
  shipping_address text not null,
  status text not null default 'Baru'
    check (status in ('Baru','Menunggu DP','Sudah DP','Produksi','Selesai','Dikirim')),
  total_amount numeric(14,2),
  dp_amount numeric(14,2),
  shipping_cost numeric(14,2),
  admin_note text,
  source text not null default 'form',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);
create index if not exists orders_customer_name_idx on public.orders (lower(customer_name));

create or replace function public.set_orders_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists orders_updated_at on public.orders;
create trigger orders_updated_at before update on public.orders
for each row execute function public.set_orders_updated_at();

alter table public.orders enable row level security;

-- Form pelanggan boleh menambahkan order, tetapi tidak boleh membaca atau mengubah data.
drop policy if exists "Public can submit orders" on public.orders;
create policy "Public can submit orders"
on public.orders for insert to anon, authenticated
with check (
  status = 'Baru'
  and source = 'form'
  and total_amount is null
  and dp_amount is null
  and shipping_cost is null
  and admin_note is null
);

-- Hanya akun yang login dapat mengelola pesanan.
-- PENTING: matikan public sign-up di Authentication > Settings.
drop policy if exists "Authenticated admins can view orders" on public.orders;
create policy "Authenticated admins can view orders"
on public.orders for select to authenticated
using (auth.uid() is not null);

drop policy if exists "Authenticated admins can update orders" on public.orders;
create policy "Authenticated admins can update orders"
on public.orders for update to authenticated
using (auth.uid() is not null)
with check (auth.uid() is not null);

grant usage on schema public to anon, authenticated;
grant insert on public.orders to anon, authenticated;
grant select, update on public.orders to authenticated;
